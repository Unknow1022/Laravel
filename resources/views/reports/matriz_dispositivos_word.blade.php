    <h1>7. Matriz de Dispositivos</h1>

    <div class="section">
        <p>A continuación se define el subconjunto representativo de dispositivos, resoluciones y navegadores más críticos para el público objetivo del Sistema de Almacén, junto con la justificación de la elección.</p>
    </div>

    <h2>Dispositivos de Prioridad Alta (Escritorio / Desktop)</h2>
    <ul>
        <li><span class="bold">Resoluciones:</span> 1920x1080 (Full HD) y 1366x768 (Laptop estándar).</li>
        <li><span class="bold">Navegadores:</span> Google Chrome (Windows/macOS), Microsoft Edge.</li>
        <li><span class="bold">Público Objetivo:</span> Administradores Generales, Supervisores y Personal de Oficina.</li>
        <li><span class="bold">Justificación:</span> Este grupo de usuarios realiza las tareas de gestión más complejas, como la configuración del sistema (Cortex Assistant), revisión extensa de catálogos, gestión de usuarios, generación de reportes detallados y la emisión inicial de vales de salida. Estas tareas requieren visualizar grandes volúmenes de datos en tablas complejas y utilizar herramientas administrativas, lo cual es óptimo y esperado en un entorno de escritorio de pantalla ancha.</li>
    </ul>

    <h2>Dispositivos de Prioridad Media (Móvil / Tablets)</h2>
    <ul>
        <li><span class="bold">Resoluciones:</span> 360x800 (ej. Samsung Galaxy / Android genérico) y 390x844 (ej. iPhone). Anchos de 629px a 768px (Tablets / iPad en vertical).</li>
        <li><span class="bold">Navegadores:</span> Google Chrome Móvil, Safari (iOS).</li>
        <li><span class="bold">Público Objetivo:</span> Operarios de Almacén, Trabajadores de Piso.</li>
        <li><span class="bold">Justificación:</span> El personal operativo necesita movilidad para consultar ubicaciones de herramientas ("Cortex Assistant"), registrar devoluciones rápidas o verificar stock mientras se desplazan físicamente por los pasillos del almacén. Es vital que funciones como la validación de vales y la consulta rápida estén adaptadas y sean funcionales en pantallas pequeñas, a pesar de que la administración profunda se realice en escritorio.</li>
    </ul>

